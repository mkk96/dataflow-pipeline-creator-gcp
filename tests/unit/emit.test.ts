import { describe, expect, it } from "vitest";
import { pyStrCode } from "../../src/lib/emit/python";
import { commentText, envLine, header, shq, yamlStr } from "../../src/lib/emit/text";
import { buildSampleData, gcsToBigquery } from "../../src/scenarios/gcsToBigquery";
import { defaultParams, sampleParams } from "../../src/scenarios/common";
import * as v from "../../src/validation/rules";

describe("safe emitters", () => {
  it("shell quoting cannot be escaped", () => {
    expect(shq("a'b; rm -rf /")).toBe(`'a'\\''b; rm -rf /'`);
    expect(shq("$(whoami)")).toBe(`'$(whoami)'`);
  });
  it("env lines are quoted and reject line breaks", () => {
    expect(envLine("PROJECT_ID", "acme-dev")).toBe("PROJECT_ID='acme-dev'");
    expect(() => envLine("X", "a\nb")).toThrow();
    expect(() => envLine("bad-key", "x")).toThrow();
  });
  it("YAML scalars are double-quoted JSON strings", () => {
    expect(yamlStr('a: "b" # c')).toBe('"a: \\"b\\" # c"');
  });
  it("Python strings escape quotes and control characters", () => {
    expect(pyStrCode('x"; import os; "')).toBe(`'x"; import os; "'`);
    expect(pyStrCode("a\nb")).toBe('"a\\nb"');
  });
  it("comments strip line breaks and bidi controls", () => {
    expect(commentText("a\nb‮c")).toBe("a b c");
  });
  it("headers follow the file type", () => {
    const h = { scenarioId: "x", generatorName: "G", generatorVersion: "1.0.0", generatedAt: "2026-01-01" };
    expect(header("main.py", h)).toMatch(/^# Generated by G v1\.0\.0/);
    expect(header("q.sql", h)).toMatch(/^-- /);
    expect(header("README.md", h)).toMatch(/^<!-- /);
    expect(header("metadata.json", h)).toBe("");
  });
});

describe("validators", () => {
  it("job names", () => {
    expect(v.jobName("prd-sales-gcs-to-bq")).toEqual(v.ok());
    expect(v.jobName("Prd_Sales").errors.length).toBe(1);
    expect(v.jobName("my-job").warnings.length).toBe(1);
  });
  it("regions reject multi-regions", () => {
    expect(v.region("US").errors.length).toBe(1);
    expect(v.region("northamerica-northeast1")).toEqual(v.ok());
  });
  it("subnetworks", () => {
    expect(v.subnetwork("regions/us-central1/subnetworks/df")).toEqual(v.ok());
    expect(v.subnetwork("https://www.googleapis.com/compute/v1/projects/host/regions/us-central1/subnetworks/df")).toEqual(v.ok());
    expect(v.subnetwork("df").errors.length).toBe(1);
  });
  it("buckets", () => {
    expect(v.gcsBucket("acme-prd-sales-landing")).toEqual(v.ok());
    expect(v.gcsBucket("acme-prd-dataflow-temp", "temp")).toEqual(v.ok());
    expect(v.gcsBucket("Bad_Bucket").errors.length).toBeGreaterThan(0);
  });
});

describe("scenario 1 sample data", () => {
  it("expected counts match the generated rows", () => {
    for (const name of Object.keys(gcsToBigquery.samples)) {
      const s = buildSampleData(sampleParams(gcsToBigquery, name));
      expect(s.expectedRows).toBe(3);
      expect(s.records.length + s.malformed.length).toBe(
        s.expectedRows + s.expectedDeadLetters + s.expectedFiltered + (s.duplicatePair ? 1 : 0),
      );
    }
  });
  it("rejects invalid filters", () => {
    const p = { ...defaultParams(gcsToBigquery), filters: ["status > 5", "nope", "amount in x,1"] };
    const issues = gcsToBigquery.validate!(p).filters;
    expect(issues.errors.length).toBeGreaterThanOrEqual(3);
  });
});
