import { describe, expect, it } from "vitest";
import { exportConfig, importConfig } from "../../src/lib/configIO";
import { fieldTooltip } from "../../src/lib/fieldTooltip";
import { suggestNames } from "../../src/lib/suggest";
import { allFields, allSections, defaultParams, sampleParams } from "../../src/scenarios/common";
import { PLANNED_SCENARIOS, SCENARIOS } from "../../src/scenarios/registry";
import { countIssues, validateParams } from "../../src/validation/validate";

const REQUIRED_LAYOUT = [
  "main.py",
  "pipeline/__init__.py",
  "pipeline/options.py",
  "pipeline/transforms.py",
  "pipeline/dofns.py",
  "pipeline/io.py",
  "tests/test_transforms.py",
  "requirements.txt",
  "setup.py",
  "flex_template/Dockerfile",
  "flex_template/metadata.json",
  "cloudbuild.yaml",
  "scripts/run_local.sh",
  "scripts/run_dataflow.sh",
  "scripts/build_flex_template.sh",
  "scripts/run_flex_template.sh",
  "config/dev.env",
  "config/stg.env",
  "config/prd.env",
  "README.md",
];

describe.each(SCENARIOS.map((s) => [s.id, s] as const))("scenario %s — contract", (_id, s) => {
  it("has unique keys, known sections and valid select defaults", () => {
    const fields = allFields(s);
    expect(new Set(fields.map((f) => f.key)).size).toBe(fields.length);
    const sections = new Set(allSections(s).map((x) => x.id));
    for (const f of fields) {
      expect(sections.has(f.section), f.key).toBe(true);
      if (f.type === "select") expect(f.options?.some((o) => o.value === f.default), f.key).toBe(true);
    }
  });

  it("every parameter has a tooltip explanation", () => {
    const p = defaultParams(s);
    expect(allFields(s).filter((f) => fieldTooltip(f, p).text.trim().length < 15).map((f) => f.key)).toEqual([]);
  });

  it("defaults validate and generate the standard layout", () => {
    const p = defaultParams(s);
    expect(countIssues(validateParams(s, p)).errors).toBe(0);
    const files = s.generate(p);
    if (s.mode === "custom") for (const path of REQUIRED_LAYOUT) expect(Object.keys(files), path).toContain(path);
  });

  it("all samples validate and generate", () => {
    expect(Object.keys(s.samples).length).toBeGreaterThan(0);
    for (const n of Object.keys(s.samples)) {
      const p = sampleParams(s, n);
      const errors = Object.entries(validateParams(s, p)).flatMap(([k, i]) => i.errors.map((e) => `${k}: ${e}`));
      expect(errors, n).toEqual([]);
      expect(Object.keys(s.generate(p)).length).toBeGreaterThan(10);
    }
  });

  it("every generated file has the header (except JSON and sample data)", () => {
    const files = s.generate(sampleParams(s, Object.keys(s.samples)[0]));
    for (const [path, content] of Object.entries(files)) {
      if (path.endsWith(".json") || path.startsWith("tests/sample_data/") || path.startsWith(".") || content === "") continue;
      expect(content, path).toMatch(/Generated by Dataflow Pipeline Creator for GCP v\d+\.\d+\.\d+/);
      expect(content, path).toContain(`Scenario: ${s.id}`);
    }
  });

  it("scripts use strict mode and never inline secrets", () => {
    const files = s.generate(defaultParams(s));
    for (const [path, content] of Object.entries(files)) {
      if (path.endsWith(".sh")) expect(content, path).toContain("set -euo pipefail");
      expect(content, path).not.toMatch(/password\s*=|private_key|BEGIN [A-Z ]*PRIVATE KEY/i);
    }
  });

  it("config export/import round-trips", () => {
    const p = sampleParams(s, Object.keys(s.samples)[0]);
    const r = importConfig(exportConfig(s, p));
    const { generated_at: _a, ...expected } = p;
    void _a;
    expect(r.params).toMatchObject(expected);
    expect(r.notes).toEqual([]);
  });

  it("suggest names follows the convention", () => {
    const p = { ...defaultParams(s), org: "acme", env: "prd", domain: "sales" };
    const sug = suggestNames(s, p);
    expect(sug.pipeline_name).toBe(`sales_${s.naming.source}_to_${s.naming.target}`);
    expect(sug.job_name).toBe(`prd-sales-${s.naming.source}-to-${s.naming.target}`);
    const r = validateParams(s, { ...p, ...sug });
    for (const k of Object.keys(sug)) expect(r[k]?.errors ?? [], k).toEqual([]);
  });
});

describe("registry", () => {
  it("covers the 15 scenarios from docs/requirements.md with unique ids", () => {
    const ids = [...SCENARIOS.map((s) => s.id), ...PLANNED_SCENARIOS.map((s) => s.id)];
    expect(new Set(ids).size).toBe(ids.length);
    expect(ids.length).toBe(15);
  });
});
