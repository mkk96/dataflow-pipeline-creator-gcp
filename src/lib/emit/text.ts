/**
 * Safe emitters for non-Python files. User input reaches generated shell,
 * YAML, .env, Dockerfile, SQL or Markdown ONLY through these helpers.
 */

/** Single-quote a value for bash ('it'\''s'). */
export function shq(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** Double-quoted YAML scalar. JSON string syntax is a valid YAML double-quoted scalar. */
export function yamlStr(value: string): string {
  return JSON.stringify(value);
}

/** KEY='value' line for a .env file that bash scripts `source`. */
export function envLine(key: string, value: string): string {
  if (!/^[A-Z][A-Z0-9_]*$/.test(key)) throw new Error(`Invalid env key ${key}`);
  if (/[\r\n\0]/.test(value)) throw new Error(`Line breaks are not allowed in ${key}`);
  return `${key}=${shq(value)}`;
}

// Control characters, line/paragraph separators and bidi overrides ("Trojan Source").
// eslint-disable-next-line no-control-regex -- matching control characters is the point
const UNSAFE_CHARS = new RegExp("[\\u0000-\\u001f\\u007f\\u2028\\u2029\\u202a-\\u202e\\u2066-\\u2069]+", "g");

/** Text for a single-line comment: strips line breaks and control characters. */
export function commentText(value: string): string {
  return value.replace(UNSAFE_CHARS, " ").trim();
}


/** Escape text for Markdown table cells / inline text. */
export function mdText(value: string): string {
  return commentText(value).replace(/([\\`*_{}[\]()<>#|!])/g, "\\$1");
}

export interface HeaderInfo {
  scenarioId: string;
  generatorName: string;
  generatorVersion: string;
  generatedAt: string;
}

export type CommentStyle = "hash" | "sql" | "html" | "none";

export function commentStyleFor(path: string): CommentStyle {
  const name = path.split("/").pop() ?? path;
  if (name.endsWith(".json")) return "none"; // JSON cannot carry comments
  if (name.endsWith(".sql")) return "sql";
  if (name.endsWith(".md")) return "html";
  return "hash"; // .py .sh .yaml .env .txt .toml Dockerfile .cfg
}

/** Header comment required by docs/standards.md on every generated file. */
export function header(path: string, h: HeaderInfo): string {
  const lines = [
    `Generated by ${h.generatorName} v${h.generatorVersion}`,
    `Scenario: ${h.scenarioId} | Generated: ${h.generatedAt}`,
  ].map(commentText);
  switch (commentStyleFor(path)) {
    case "hash":
      return lines.map((l) => `# ${l}`).join("\n") + "\n";
    case "sql":
      return lines.map((l) => `-- ${l}`).join("\n") + "\n";
    case "html":
      return `<!-- ${lines.join(" | ")} -->\n`;
    default:
      return "";
  }
}

/** Prepend the header, keeping a shebang (#!) as the very first line. */
export function withHeader(path: string, content: string, h: HeaderInfo): string {
  const hdr = header(path, h);
  if (!hdr) return content;
  if (content.startsWith("#!")) {
    const nl = content.indexOf("\n");
    return content.slice(0, nl + 1) + hdr + content.slice(nl + 1);
  }
  return hdr + content;
}
