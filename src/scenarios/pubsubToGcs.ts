/**
 * Scenario 10 — Pub/Sub → parse JSON → transform builder (scenario 1's mapping/casting)
 * → fixed event-time windows → Avro / Parquet / JSON-lines files on GCS, with windowed
 * dead-letter files.
 *
 * Beam 2.77.0 APIs used (verified against the installed SDK):
 *   ReadFromPubSub(...); beam.WindowInto(FixedWindows, trigger=AfterWatermark(late=
 *   AfterCount(1)), allowed_lateness, DISCARDING); apache_beam.io.fileio.WriteToFiles(
 *   path, file_naming, sink, shards) with custom FileSink classes (fastavro Writer,
 *   pyarrow ParquetWriter, TextSink). WriteToFiles supports unbounded input; its default
 *   naming has no pane index, so the file naming adds a unique id per file so a late
 *   firing never overwrites the on-time files of the same window. (Windowed
 *   WriteToText/WriteToAvro/WriteToParquet exist for unbounded input in 2.77.0 too, but
 *   their names also lack the pane, and they cannot write a single format-agnostic sink.)
 */
